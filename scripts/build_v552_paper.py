def numeric(g, name):
    v = pd.to_numeric(g['features/' + name][:], errors='coerce').astype(float)
    valid = g['validity_masks/features/' + name][:].astype(bool) & np.isfinite(v)
    return np.where(valid, v, np.nan)


def cohort_tables():
    blob = None
    with tarfile.open(DATA_ARCHIVE, 'r|gz') as archive:
        for member in archive:
            if member.name == 'cpetlite_paper_standard_v5_5_2_20261019/dataset.h5':
                blob = archive.extractfile(member).read()
    assert blob is not None and hashlib.sha256(blob).hexdigest() == DATA_SHA
    frames, availability, support, bounds, source_counts, split_ids = [], [], [], {}, {}, {}
    source_phases = {}
    with h5py.File(io.BytesIO(blob), 'r') as h:
        for split in ['train', 'val', 'test']:
            g = h['splits/' + split]
            meta = g['metadata_table']
            ids = meta['Examination_ID'].asstr()[:]
            assert len(ids) == len(set(ids)) == COUNTS[split]
            split_ids[split] = set(ids)
            d = pd.DataFrame({'id': ids, 'centre': meta['Institute_Name'].asstr()[:]})
            for name in ['Age', 'Gender', 'Height_cm', 'Weight_kg']:
                d[name] = pd.to_numeric(meta[name][:], errors='coerce')
            rows = pd.DataFrame({'id': g['features/Examination_ID'].asstr()[:]})
            for name in ['Time', 'Power_Load', 'VO2']:
                rows[name] = numeric(g, name)
            grouped = rows.groupby('id', sort=False)
            a = grouped.agg(tmin=('Time', 'min'), tmax=('Time', 'max'), workload=('Power_Load', 'max'), max_vo2=('VO2', 'max'))
            d = d.join(a, on='id', validate='one_to_one')
            d['duration'] = d.tmax - d.tmin
            d['split'] = split
            frames.append(d)
            if split == 'test':
                source_counts = grouped.Time.count().to_dict()
            bounds[split] = d.duration.median()
            phase = numeric(g, 'Load_Phase')
            if split == 'test':
                rows['phase'] = np.where(g['validity_masks/features/Load_Phase'][:].astype(bool), phase, np.nan)
                for exam, group in rows.groupby('id', sort=False):
                    selected = group[np.isfinite(group.Time)].sort_values('Time', kind='stable')
                    if len(selected) > 192:
                        selected = selected.iloc[np.rint(np.linspace(0, len(selected) - 1, 192)).astype(int)]
                    source_phases[str(exam)] = selected.phase.to_numpy()
            for name in ['HR', 'SpO2', 'Bf', 'VO2', 'VCO2', 'VE']:
                valid = np.isfinite(numeric(g, name))
                any_count = pd.Series(valid).groupby(rows.id).any().sum()
                stages = pd.DataFrame({'id': rows.id, 'phase': phase, 'valid': valid}).groupby(['id', 'phase']).valid.any().unstack(fill_value=False).reindex(columns=[0, 1, 2], fill_value=False)
                availability.append([split, name, int(any_count), int(stages.all(axis=1).sum()), f'{100 * valid.mean():.1f}'])
            targets = g['targets/raw']
            tid = targets['Examination_ID'].asstr()[:]
            at = pd.to_numeric(targets['Time_at_AT'][:], errors='coerce')
            valid = g['validity_masks/targets/Time_at_AT'][:].astype(bool) & g['supervision_eligibility/at'][:].astype(bool) & np.isfinite(at)
            target = pd.DataFrame({'id': tid, 'at': at, 'eligible': valid}).join(d.set_index('id')[['centre', 'tmin', 'tmax']], on='id')
            target['outside'] = valid & ((target['at'] < target.tmin - .001) | (target['at'] > target.tmax + .001))
            for centre, v in target.groupby('centre'):
                support.append({'split': split, 'centre': centre, 'eligible': int(v.eligible.sum()), 'outside': int(v.outside.sum())})
    assert all(not split_ids[a] & split_ids[b] for a, b in [('train', 'val'), ('train', 'test'), ('val', 'test')])
    data = pd.concat(frames, ignore_index=True)
    def iqr(v):
        v = np.asarray(v, dtype=float); v = v[np.isfinite(v)]
        if not len(v):
            return 'NA'
        q = np.quantile(v, [.25, .5, .75])
        return f'{q[1]:.1f} [{q[0]:.1f}--{q[2]:.1f}]'
    splits = ['train', 'val', 'test']
    rows = [['Examinations', *[f'{COUNTS[s]:,}' for s in splits]]]
    for name, label in [('Age', 'Age (years)'), ('Height_cm', 'Height (cm)'), ('Weight_kg', 'Weight (kg)'),
                        ('duration', 'Recorded duration (s)'), ('workload', 'Maximum recorded workload (W)'),
                        ('max_vo2', 'Maximum recorded VO$_2$ (ml/min)')]:
        rows.append([label, *[iqr(data.loc[data.split == s, name]) for s in splits]])
    sex = []
    for s in splits:
        v = data.loc[data.split == s, 'Gender']; valid = v.isin([0, 1]); male = int((v[valid] == 1).sum())
        sex.append(f'{male:,} ({100 * male / valid.sum():.1f})' if valid.any() else 'NA')
    rows.append(['Recorded male sex, n (\\%)', *sex])
    table('cohort', ['Characteristic', 'Training', 'Validation', 'External'], rows)
    counts = pd.crosstab(data.centre, data.split).reindex(columns=splits, fill_value=0)
    table('centres', ['Centre', 'Training', 'Validation', 'External'], [[CENTRES[c], *map(int, v)] for c, v in counts.iterrows()])
    table('availability', ['Split', 'Channel', 'Any valid position, n', 'All three stages, n', 'Valid cells (\\%)'], availability)
    table('at_support', ['Centre', 'Training', 'Validation', 'External'],
          [[CENTRES[c], *[next((f"{r['eligible']} / {r['outside']}" for r in support if r['centre'] == c and r['split'] == s), '--') for s in splits]] for c in sorted(CENTRES)])
    write_json(TAB / 'at_support_audit.json', {'tolerance_s': .001, 'counts': support})
    # Only aggregate cohort values are exported, never patient-level metadata.
    with (TAB / 'cohort_source.csv').open('w') as output:
        writer = csv.writer(output); writer.writerow(['characteristic', 'train', 'validation', 'external']); writer.writerows(rows)
    return source_counts, support, bounds, source_phases


def save_figure(fig, name):
    require_matplotlib_panel_alignment(fig, json_out=OUT / (name + '.alignment.json'), strict=True)
    for extension in ['.svg', '.pdf', '.png']:
        fig.savefig(OUT / (name + extension), dpi=600, bbox_inches='tight', facecolor='white')
    plt.close(fig)


def figures(experiments, z, source_counts, source_phases):
    fig, axs = plt.subplots(2, 3, figsize=(10, 5.6))
    fig.subplots_adjust(left=.08, right=.99, bottom=.08, top=.89, hspace=.5, wspace=.5)
    for row, domain in enumerate(['internal', 'external']):
        for col, (key, label) in enumerate([('primary_trajectory_rmse', 'Standardized core RMSE'),
                                           ('at_time_s_mae', 'AT-time MAE (s)'), ('vo2peak_mae', 'Peak MAE (ml/kg/min)')]):
            ax = axs[row, col]
            for offset, (stage, title, color) in enumerate([('measured', 'Measured-label supervision', '#3978B7'),
                                                         ('ordinary_package', 'Teacher-generated supervision', '#009C99')]):
                q = [experiments[a]['summary'][stage + ':' + domain][key] for a in ['Transformer', 'GRU']]
                ax.bar(np.arange(2) + (offset - .5) * .32, [v['mean'] for v in q], width=.30,
                       yerr=[v['sd'] for v in q], capsize=3, label=title, color=color)
            ax.set_xticks([0, 1], ['Transformer', 'GRU']); ax.set_ylabel(label)
            ax.set_title('Internal validation' if row == 0 else 'External centre'); ax.set_ylim(bottom=0)
    handles, labels = axs[0, 0].get_legend_handles_labels()
    fig.legend(handles, labels, loc='upper center', bbox_to_anchor=(.5, .995), ncol=2)
    save_figure(fig, 'performance')
    names = list(z['channel_names'].astype(str)); idx = [names.index(k) for k in ['VO2', 'VCO2', 'VE']]
    valid = (z['task_mask'][..., None] > 0) & (z['target_channel_mask'][..., idx] > 0)
    squared = (z['trajectory_pred'][..., idx].astype(float) - z['trajectory_target'][..., idx]) ** 2
    denom = valid.sum((1, 2)); errors = np.sqrt(np.divide(np.where(valid, squared, 0).sum((1, 2)), denom,
                out=np.full(len(denom), np.nan), where=denom > 0))
    eligible = np.flatnonzero(np.isfinite(errors)); order = eligible[np.argsort(errors[eligible], kind='stable')]
    chosen = [int(order[round(q * (len(order) - 1))]) for q in [.25, .5, .9]]
    fig, axs = plt.subplots(3, 4, figsize=(10, 6.7), sharex=True)
    fig.subplots_adjust(left=.10, right=.99, bottom=.09, top=.89, hspace=.45, wspace=.35)
    rows, cases = [], []
    phase_colors = {0: '#E5E7EB', 1: '#F9E7BE', 2: '#DBEAEF'}
    for row, (i, percentile) in enumerate(zip(chosen, [25, 50, 90])):
        count = min(int(source_counts[str(z['exam_id'][i])]), 192)
        x = np.arange(192) * 100 / max(count - 1, 1)
        phases = source_phases[str(z['exam_id'][i])]
        assert len(phases) == count, 'Illustration phase/source support mismatch'
        cases.append({'percentile': percentile, 'case_code': hashlib.sha256(str(z['exam_id'][i]).encode()).hexdigest()[:10],
                      'core_rmse': float(errors[i]), 'source_positions': count})
        for col, channel in enumerate(['VO2', 'VCO2', 'VE', 'RER']):
            ax = axs[row, col]; j = names.index(channel)
            boundaries = np.r_[0, (x[:count - 1] + x[1:count]) / 2, 100]
            for t, phase in enumerate(phases):
                if phase in phase_colors:
                    ax.axvspan(boundaries[t], boundaries[t + 1], color=phase_colors[phase],
                               alpha=.50, linewidth=0, zorder=0)
            mask = (z['task_mask'][i] > 0) & (z['target_channel_mask'][i, :, j] > 0)
            mask[count:] = False
            for key, label, color in [('trajectory_target', 'CPET reference', '#374552'),
                                      ('trajectory_pred', 'Teacher-supervised Transformer', '#009C99')]:
                ax.plot(x, np.where(mask, z[key][i, :, j], np.nan), lw=1.2, color=color, label=label)
            ax.set_xlim(0, 100)
            if row == 0:
                ax.set_title(channel)
            if col == 0:
                ax.set_ylabel(f'P{percentile} · core RMSE {errors[i]:.3f}\nStandardized value')
            if row == 2:
                ax.set_xlabel('Retained-row position (%)')
            for t in range(count):
                rows.append([percentile, channel, t, float(x[t]), int(mask[t]),
                             float(z['trajectory_target'][i, t, j]) if mask[t] else None,
                             float(z['trajectory_pred'][i, t, j]) if mask[t] else None,
                             int(phases[t]) if phases[t] in phase_colors else None])
    handles, labels = axs[0, 0].get_legend_handles_labels()
    from matplotlib.patches import Patch
    handles += [Patch(facecolor=color, alpha=.5) for color in phase_colors.values()]
    labels += ['Source rest', 'Source exercise', 'Source recovery']
    fig.legend(handles, labels, loc='upper center', bbox_to_anchor=(.5, 1.01), ncol=3, fontsize=9)
    save_figure(fig, 'representative_curves')
    with (TAB / 'curve_source.csv').open('w') as output:
        writer = csv.writer(output); writer.writerow(['percentile', 'channel', 'position', 'recording_position_pct', 'valid', 'reference_standardized', 'prediction_standardized', 'source_phase']); writer.writerows(rows)
    return {'seed': 42, 'arm': 'ordinary_package', 'domain': 'external', 'rule': 'stable per-examination core RMSE ranks', 'cases': cases}


