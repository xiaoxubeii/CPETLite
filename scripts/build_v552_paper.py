def recompute(z):
    names = list(z['channel_names'].astype(str))
    idx = [names.index(k) for k in ['VO2', 'VCO2', 'VE']]
    valid = (z['task_mask'][..., None] > 0) & (z['target_channel_mask'][..., idx] > 0)
    residual = z['trajectory_pred'][..., idx].astype(float) - z['trajectory_target'][..., idx]
    assert np.isfinite(residual[valid]).all() and valid.any()
    core = np.sqrt(np.square(residual[valid]).mean())
    am = (z['at_metric_mask'] > 0) & np.isfinite(z['at_target_s'])
    at = z['time_start_s'].astype(float) + z['duration_s'] * z['at_pred_norm'].astype(float)
    pmask = (z['vo2peak_mask'] > 0) & np.isfinite(z['vo2peak_target'])
    return dict(primary_trajectory_rmse=float(core), at_time_s_mae=float(np.abs(at[am] - z['at_target_s'][am]).mean()),
                vo2peak_mae=float(np.abs(z['vo2peak_pred'][pmask].astype(float) - z['vo2peak_target'][pmask]).mean()))


def read_accepted_archive():
    assert digest(ARCHIVE) == ARCHIVE_SHA, 'Result archive changed'
    acceptance = json.loads((ARCHIVE.parent / 'ACCEPTANCE.json').read_text())
    assert acceptance['status'] == 'verified'
    completion = json.loads((COLLECTION / 'COMPLETION_ACCEPTANCE.json').read_text())
    assert completion['status'] == 'verified'
    assert (completion['student_fits'], completion['evaluations'], completion['teacher_epochs']) == (15, 30, 30)
    assert completion['archive_sha256'] == ARCHIVE_SHA
    assert completion['package_backup_sha256'] == PACKAGE_SHA
    fits = json.loads((COLLECTION / 'ACTUAL_FIT_AUDIT.json').read_text())
    assert fits['all_fits_accepted'] and len(fits['accepted']) == 15
    assert not fits['pending'] and not fits['failed']
    teacher = json.loads((COLLECTION / 'TEACHER_FIT_AUDIT.json').read_text())
    assert teacher['verified'] and teacher['epochs'] == 30 and teacher['package_teacher_binding_matches']
    collection = json.loads((ARCHIVE.parent / 'COLLECTION_RECEIPT.json').read_text())
    assert collection['status'] == 'verified'
    inputs = json.loads((COLLECTION / 'POSTRUN_INPUT_AUDIT.json').read_text())
    assert inputs['status'] == 'verified' and not inputs['mismatches']
    payload, member_hashes, predictions, configs, code = {}, {}, {}, {}, {}
    # One sequential pass; never extract paths supplied by a tar member.
    with tarfile.open(ARCHIVE, 'r|gz') as archive:
        for member in archive:
            name = member.name
            if not member.isfile() or '_smoke' in name:
                continue
            is_eval = any(name.startswith(f'foundation/artifacts/eval/{EXPERIMENT}{suffix}/')
                          for suffix in ['', '_direct', '_gru'])
            is_fit = name.startswith(f'foundation/artifacts/models/{EXPERIMENT}_')
            is_config = name.startswith('foundation/configs/') and EXPERIMENT in name and name.endswith('.yaml')
            is_code = name.startswith('foundation/src/cpet_foundation/') and name.endswith('.py')
            is_script = name.startswith('foundation/scripts/') and name.endswith('.py')
            if not (is_eval or is_fit or is_config or is_code or is_script):
                continue
            stream = archive.extractfile(member)
            if is_fit and name.endswith('/model.pt'):
                member_hashes[name] = hashlib.file_digest(stream, 'sha256').hexdigest()
                continue
            if not (name.endswith(('.json', '.npz', '.yaml', '.py', '.md'))):
                continue
            blob = stream.read()
            member_hashes[name] = hashlib.sha256(blob).hexdigest()
            if name.endswith('.json'):
                payload[name] = json.loads(blob)
            elif is_config:
                configs[name] = blob
            elif is_code or is_script:
                code[name] = blob
            elif name.endswith('_predictions.npz') and is_eval:
                with np.load(io.BytesIO(blob), allow_pickle=False) as a:
                    z = {k: a[k] for k in a.files}
                expected = 1270 if '_internal_' in name else 2385
                assert len(z['exam_id']) == len(set(z['exam_id'])) == expected
                metrics = recompute(z)
                metric_name = name.replace('_predictions.npz', '.json')
                predictions[name] = {'metrics': metrics, 'metric_name': metric_name,
                                     'at_count': int((z['at_metric_mask'] > 0).sum()),
                                     'peak_count': int((z['vo2peak_mask'] > 0).sum())}
                if name == f'foundation/artifacts/eval/{EXPERIMENT}_direct/ordinary_package_seed42_external_predictions.npz':
                    predictions['curve_arrays'] = z
    root = f'foundation/artifacts/eval/{EXPERIMENT}'
    audit, replay = payload[root + '/FINAL_AUDIT.json'], payload[root + '/PREDICTION_AUDIT.json']
    require_complete(audit, replay)
    arrays = predictions.pop('curve_arrays')
    assert len(predictions) == 30
    for name, record in predictions.items():
        q = payload[record['metric_name']]
        for key, value in record['metrics'].items():
            assert np.isclose(q[key], value, atol=2e-5, rtol=2e-6), (name, key)
        assert q['at_evaluable_count'] == record['at_count']
        assert q['vo2peak_evaluable_count'] == record['peak_count']
    for name, q in payload.items():
        if name.startswith(root) and not '/models/' in name:
            relative = name.split('artifacts/eval/', 1)[1]
            write_json(EVIDENCE / relative, q)
    capsule = TAB / 'reproducibility'
    capsule.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(capsule / 'cpetlite-v552-code-config.zip', 'w', zipfile.ZIP_DEFLATED) as output:
        for name, blob in sorted({**configs, **code}.items()):
            output.writestr(str(PurePosixPath(name).relative_to('foundation')), blob)
    write_json(capsule / 'manifest.json', {'archive_sha256': ARCHIVE_SHA,
               'files': {k: member_hashes[k] for k in sorted({**configs, **code})},
               'contents': 'Frozen execution code/configurations, no clinical arrays, packages, checkpoints or predictions'})
    return payload, member_hashes, arrays, predictions, configs


def require_records(payload, hashes):
    experiments = {}
    for arch in ['direct', 'gru']:
        directory = f'foundation/artifacts/eval/{EXPERIMENT}_{arch}'
        q = payload[directory + '/summary.json']
        expected = {(stage, seed, domain) for a, stage in ARMS if a == arch
                    for seed in SEEDS for domain in ['internal', 'external']}
        assert len(q['records']) == len(expected)
        assert {(r['stage'], r['seed'], r['domain']) for r in q['records']} == expected
        for r in q['records']:
            stem = f"{r['stage']}_seed{r['seed']}_{r['domain']}"
            ev = payload[f'{directory}/{stem}_manifest.json']
            n, at, peak = (1270, 909, 1270) if r['domain'] == 'internal' else (2385, 2375, 2385)
            assert ev['loaded_examinations'] == ev['requested_examinations'] == n
            assert ev['source_h5_sha256'] == ev['split_sha256'] == DATA_SHA
            assert (r['at_count'], r['peak_count']) == (at, peak)
            checkpoint = 'foundation/' + ev['checkpoint'].split('/foundation/', 1)[1]
            assert hashes[checkpoint] == ev['checkpoint_sha256']
            fit = payload[str(PurePosixPath(checkpoint).with_name('manifest.json'))]
            assert fit['train_samples'] == 11404 and fit['validation_samples'] == 1270
            c = fit['training_control']
            assert c['max_epochs'] == 150 and c['restore_best_weights']
            if r['stage'] != 'measured':
                assert not fit['raw_cpet_opened_by_student_trainer']
                assert not fit['measured_training_targets_available']
                assert fit['distillation_package_sha256'] == PACKAGE_SHA
            metric = payload[f'{directory}/{stem}.json']
            for key, _ in METRICS:
                assert np.isclose(metric[key], r['metrics'][key], rtol=1e-12)
        for stage in {s for a, s in ARMS if a == arch}:
            for domain in ['internal', 'external']:
                records = [r for r in q['records'] if r['stage'] == stage and r['domain'] == domain]
                assert sorted(r['seed'] for r in records) == SEEDS
                for key, _ in METRICS:
                    values = [r['metrics'][key] for r in records]
                    summary = q['summary'][stage + ':' + domain][key]
                    assert np.isclose(np.mean(values), summary['mean'], rtol=1e-12)
                    assert np.isclose(np.std(values, ddof=1), summary['sd'], rtol=1e-12)
        experiments[ARCHS[arch]] = q
    return experiments


